"""Generate the femapp element type table from the Gmsh API.

Usage (needs the Gmsh Python package, e.g. `pip install gmsh`):

    python tools/generate_element_types.py

Writes:
    src/core/include/fem/core/element_types.inc   X-macro list of the types
    src/core/element_reference_coordinates.inc    reference node coordinates

Gmsh is used only as a tool here: the output is data about the .msh format
(node counts, orders, reference coordinates), not Gmsh code. See
specs/features/003-mesh-model/design.md, section 5.1.
"""

import pathlib
import sys

import gmsh

ROOT = pathlib.Path(__file__).resolve().parent.parent
TYPES_FILE = ROOT / "src/core/include/fem/core/element_types.inc"
COORDS_FILE = ROOT / "src/core/element_reference_coordinates.inc"

# Gmsh family name -> (femapp family, enum prefix). Order defines the enum order.
FAMILIES = {
    "Point": ("Point", "Point"),
    "Line": ("Line", "Line"),
    "Triangle": ("Triangle", "Tri"),
    "Quadrilateral": ("Quadrilateral", "Quad"),
    "Tetrahedron": ("Tetrahedron", "Tet"),
    "Hexahedron": ("Hexahedron", "Hex"),
    "Prism": ("Wedge", "Wedge"),
    "Pyramid": ("Pyramid", "Pyramid"),
}
FAMILY_ORDER = list(FAMILIES)

# Incomplete hexahedra of order 4 to 9 and incomplete pyramids of order 3 to 9:
# Gmsh describes them, but gmsh.model.mesh.addElementsByType crashes for them in
# Gmsh 4.15.2, so they never appear in files written by Gmsh. Left out by
# decision of the maintainer (design section 5.1).
GMSH_CANNOT_CREATE = {100, 101, 102, 103, 104, 105, 125, 126, 127, 128, 129, 130, 131}


def collect():
    types = []
    for gmsh_type in range(1, 1000):
        try:
            name, dim, order, node_count, coords, vertex_count = (
                gmsh.model.mesh.getElementProperties(gmsh_type))
        except Exception:  # Gmsh raises for numbers it does not define
            continue
        family_name = name.split()[0]
        # Fixed-size types only: no polygons, polyhedra, XFEM or the order-0
        # one-node elements (design section 5.1).
        if family_name not in FAMILIES or node_count < 1:
            continue
        if order == 0 and family_name != "Point":
            continue
        if gmsh_type in GMSH_CANNOT_CREATE:
            continue

        family, prefix = FAMILIES[family_name]
        suffix = name.split()[1] if " " in name else "1"
        enum_name = prefix + suffix
        points = []
        for i in range(node_count):
            local = list(coords[i * dim:(i + 1) * dim]) if dim > 0 else []
            points.append((local + [0.0, 0.0, 0.0])[:3])
        types.append({
            "enum": enum_name,
            "family": family,
            "family_index": FAMILY_ORDER.index(family_name),
            "dim": dim,
            "order": order,
            "nodes": node_count,
            "vertices": vertex_count,
            "gmsh": gmsh_type,
            "points": points,
        })
    types.sort(key=lambda t: (t["family_index"], t["order"], t["nodes"], t["gmsh"]))
    return types


def number(value):
    text = repr(float(value))
    return "0.0" if text == "-0.0" else text


def write(types, version):
    header = (f"// Generated by tools/generate_element_types.py from Gmsh {version}.\n"
              "// Do not edit.\n")

    lines = [header,
             "// FEM_ELEMENT_TYPE(name, family, dimension, order, nodeCount, vertexCount, gmshType)",
             ""]
    for t in types:
        lines.append(f"FEM_ELEMENT_TYPE({t['enum']}, {t['family']}, {t['dim']}, {t['order']}, "
                     f"{t['nodes']}, {t['vertices']}, {t['gmsh']})")
    TYPES_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    lines = [header,
             "// Node coordinates (u, v, w) in Gmsh's reference element, in local node order.",
             ""]
    for t in types:
        lines.append(f"inline constexpr std::array<std::array<double, 3>, {t['nodes']}> "
                     f"kReference{t['enum']} = {{{{")
        for p in t["points"]:
            lines.append(f"    {{{number(p[0])}, {number(p[1])}, {number(p[2])}}},")
        lines.append("}};")
        lines.append("")
    COORDS_FILE.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    gmsh.initialize()
    gmsh.option.setNumber("General.Terminal", 0)
    try:
        version = gmsh.__version__
        types = collect()
    finally:
        gmsh.finalize()

    names = [t["enum"] for t in types]
    if len(set(names)) != len(names):
        sys.exit("duplicate enum names: " + ", ".join(sorted(n for n in names if names.count(n) > 1)))
    write(types, version)
    print(f"{len(types)} element types from Gmsh {version}")


if __name__ == "__main__":
    main()
